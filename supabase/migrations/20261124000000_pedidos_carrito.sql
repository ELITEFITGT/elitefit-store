-- =====================================================================================
-- MIGRACIÓN: pedidos de la tienda en línea (ELITEFIT)
--
-- Crea las tablas donde la tienda registra cada pedido confirmado:
--   - public.pedidos_carrito           → encabezado (cliente, entrega, totales, estado)
--   - public.pedidos_carrito_detalles  → artículos del pedido (variante, talla, color, cantidad, precio)
--
-- Quién escribe: SOLO el servidor de la tienda (POST /api/pedidos), con SUPABASE_SECRET_KEY.
-- Quién lee: tu sistema interno (con la secret key o con las políticas opcionales del final).
--
-- Es idempotente: se puede correr varias veces. Si una tabla, regla o índice ya existe, no se toca.
-- Requisitos en el proyecto destino:
--   - La tabla public.variantes (catálogo) debe existir: los detalles apuntan a variantes.id.
--   - Un usuario en Authentication → Users para ORDER_USUARIO_ID (los pedidos web quedan a su nombre).
--
-- Cómo correrla:
--   - Panel de Supabase → SQL Editor → pegar este archivo → Run.
--   - O con Supabase CLI:  supabase db push   (desde la carpeta del proyecto, enlazado a dev o prd).
-- =====================================================================================

begin;

-- -------------------------------------------------------------------------------------
-- 1. Encabezado del pedido
-- -------------------------------------------------------------------------------------
create table if not exists public.pedidos_carrito (
  id                    uuid primary key default gen_random_uuid(),
  -- Número visible para el cliente ("Pedido #123"). Lo asigna la base; puede saltar números.
  numero_pedido         bigint generated by default as identity,
  -- Usuario de Supabase Auth al que se asignan los pedidos web (ORDER_USUARIO_ID).
  usuario_id            uuid not null references auth.users (id),
  -- Identificador del intento de compra: evita registrar dos veces el mismo pedido.
  checkout_id           uuid not null,
  nombre_cliente        text not null,
  telefono_cliente      text not null,
  -- 'envio_domicilio' | 'retiro_tienda'
  metodo_entrega        text not null,
  departamento          text,
  municipio             text,
  direccion             text,
  referencia_direccion  text,
  -- Tu sistema lo cambia al atender el pedido (pendiente → confirmado → enviado…).
  estado                text not null default 'pendiente',
  subtotal              numeric(12, 2) not null,
  costo_envio           numeric(12, 2) not null default 0,
  -- Calculado por la base: no se escribe.
  total                 numeric(12, 2) generated always as (subtotal + costo_envio) stored,
  creado_en             timestamptz not null default now()
);

comment on table public.pedidos_carrito is 'Pedidos confirmados desde la tienda en línea. Los escribe /api/pedidos.';

-- -------------------------------------------------------------------------------------
-- 2. Artículos del pedido
-- -------------------------------------------------------------------------------------
create table if not exists public.pedidos_carrito_detalles (
  id               uuid primary key default gen_random_uuid(),
  pedido_id        uuid not null references public.pedidos_carrito (id) on delete cascade,
  variante_id      uuid not null references public.variantes (id),
  -- Copia de los datos al momento de la compra (si luego cambia el catálogo, el pedido conserva lo vendido).
  nombre_producto  text not null,
  talla            text not null,
  color            text not null,
  cantidad         integer not null,
  precio_unitario  numeric(12, 2) not null,
  -- Calculado por la base: no se escribe.
  subtotal_linea   numeric(12, 2) generated always as (cantidad * precio_unitario) stored
);

comment on table public.pedidos_carrito_detalles is 'Artículos de cada pedido de la tienda en línea.';

-- -------------------------------------------------------------------------------------
-- 3. Reglas (se crean solo si no existen)
-- -------------------------------------------------------------------------------------
do $$
begin
  -- Un mismo intento de compra no puede registrarse dos veces.
  if not exists (select 1 from pg_constraint where conname = 'pedidos_carrito_checkout_id_key') then
    alter table public.pedidos_carrito add constraint pedidos_carrito_checkout_id_key unique (checkout_id);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'pedidos_carrito_numero_pedido_key') then
    alter table public.pedidos_carrito add constraint pedidos_carrito_numero_pedido_key unique (numero_pedido);
  end if;

  -- Envío a domicilio exige dirección completa; retiro en tienda no.
  if not exists (select 1 from pg_constraint where conname = 'pedidos_carrito_datos_entrega_validos') then
    alter table public.pedidos_carrito add constraint pedidos_carrito_datos_entrega_validos check (
      (metodo_entrega = 'envio_domicilio'
        and nullif(btrim(departamento), '') is not null
        and nullif(btrim(municipio), '') is not null
        and nullif(btrim(direccion), '') is not null)
      or metodo_entrega = 'retiro_tienda'
    );
  end if;

  if not exists (select 1 from pg_constraint where conname = 'pedidos_carrito_montos_validos') then
    alter table public.pedidos_carrito add constraint pedidos_carrito_montos_validos check (subtotal >= 0 and costo_envio >= 0);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'pedidos_carrito_detalles_valores_validos') then
    alter table public.pedidos_carrito_detalles add constraint pedidos_carrito_detalles_valores_validos check (cantidad > 0 and precio_unitario >= 0);
  end if;
end $$;

-- -------------------------------------------------------------------------------------
-- 4. Índices para consultar pedidos desde tu sistema
-- -------------------------------------------------------------------------------------
create index if not exists pedidos_carrito_creado_en_idx on public.pedidos_carrito (creado_en desc);
create index if not exists pedidos_carrito_estado_idx on public.pedidos_carrito (estado);
create index if not exists pedidos_carrito_detalles_pedido_id_idx on public.pedidos_carrito_detalles (pedido_id);

-- -------------------------------------------------------------------------------------
-- 5. Seguridad: nadie escribe ni lee desde el navegador.
--    La secret key (servidor de la tienda y tu sistema) ignora RLS, así que sigue funcionando.
-- -------------------------------------------------------------------------------------
alter table public.pedidos_carrito enable row level security;
alter table public.pedidos_carrito_detalles enable row level security;

revoke all on public.pedidos_carrito from anon;
revoke all on public.pedidos_carrito_detalles from anon;

commit;

